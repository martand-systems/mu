#!/bin/bash
# S2 probe: PrusaSlicer 2.9.7 from Flathub pinned by commit, in a user flatpak dir; CLI slicing headless.
. /w/tools/s2/common.sh
APP_COMMIT=22caa5995fef8170cbed1d404f993996e5552e47159391666a7b096a85d8f641
RT_COMMIT=4337a389125f814785bd83f4ace01da5b6baa80fdcf5a9c81e60dcd03896c067
apt_install $APT_LIST dbus
cat > /home/mu/ps.sh <<EOS
set -euo pipefail
export FLATPAK_USER_DIR=/home/mu/store/flatpak
flatpak --user remote-add --if-not-exists flathub https://dl.flathub.org/repo/flathub.flatpakrepo
flatpak --user install -y --noninteractive flathub com.prusa3d.PrusaSlicer >/dev/null
flatpak --user update -y --noninteractive --commit=$APP_COMMIT com.prusa3d.PrusaSlicer >/dev/null || true
flatpak --user update -y --noninteractive --commit=$RT_COMMIT runtime/org.gnome.Platform/x86_64/50 >/dev/null || true
flatpak --user info --show-commit com.prusa3d.PrusaSlicer
flatpak --user info --show-commit runtime/org.gnome.Platform/x86_64/50
du -sm \$FLATPAK_USER_DIR | cut -f1 | sed 's/^/flatpak_MB=/'
mkdir -p /home/mu/ps-data
flatpak run --user --command=prusa-slicer --filesystem=host --nosocket=x11 --nosocket=wayland --env=LC_ALL=C.UTF-8 com.prusa3d.PrusaSlicer \
  --datadir /home/mu/ps-data --export-gcode --load /w/benchmarks/slice-print/profile_PETG-CF_0.4_0.2.ini /w/tools/s2/fixtures/plate.stl -o /home/mu/plate.gcode
grep -E "^; (generated by|filament used \[g\]|estimated printing time \(normal)" /home/mu/plate.gcode
echo layers=\$(grep -c "^;LAYER_CHANGE" /home/mu/plate.gcode) lines=\$(wc -l < /home/mu/plate.gcode)
EOS
chown mu /home/mu/ps.sh
log "flatpak install (pinned commits) + slice as user mu"
as_user dbus-run-session -- bash /home/mu/ps.sh 2>&1 | tee "$OUT/prusaslicer.txt"
grep -q "filament used" "$OUT/prusaslicer.txt" && res prusaslicer ok
log done
