#!/bin/bash
# S2 probe: PrusaSlicer 2.9.7 from Flathub pinned by commit, through μ's flatpak download cache (install/flatpak.sh):
# flatpak downloads straight at the pinned commits into the cache (interrupted once, then resumed, with a second fetch waiting on the lock), then two flatpak installations
# built from the cache with no network at all (unshare -n), then headless CLI slicing.
. /w/tools/s2/common.sh
REF=app/com.prusa3d.PrusaSlicer/x86_64/stable
APP_COMMIT=22caa5995fef8170cbed1d404f993996e5552e47159391666a7b096a85d8f641
RTREF=runtime/org.gnome.Platform/x86_64/50
RT_COMMIT=4337a389125f814785bd83f4ace01da5b6baa80fdcf5a9c81e60dcd03896c067
apt_install $APT_LIST
# containers have no system D-Bus (WSL2 with systemd has one); flatpak's deploy step talks to it
mkdir -p /run/dbus && dbus-daemon --system --fork && log "system dbus started"
res ostree "$(ostree --version | sed -n 's/^ *Version: *//p' | tr -d "'")"
res flatpak "$(flatpak --version)"
rx() { cat /sys/class/net/eth0/statistics/rx_bytes 2>/dev/null || echo 0; }
cat > /home/mu/lib.sh <<'EOS'
set -Eeuo pipefail
export MU_CACHE=/home/mu/cache LC_ALL=C.UTF-8
fail() { echo "error: $*" >&2; exit 1; }
note() { echo "note: $*" >&2; }
. /w/install/download.sh
. /w/install/flatpak.sh
KEY=/w/toolchain/linux-64/flathub.gpg; URL=https://dl.flathub.org/repo/
EOS
chown mu /home/mu/lib.sh
u() { as_user dbus-run-session -- bash -c ". /home/mu/lib.sh; $*"; }

log "cold pull of the runtime, interrupted after 20 s"
r0=$(rx); t=$SECONDS
( u "fp_fetch $RTREF $RT_COMMIT \$URL \$KEY" > "$OUT/pull-interrupted.txt" 2>&1 ) & p=$!
# like Ctrl-C / a closed terminal: the installer and its ostree pull both stop
sleep 20; pkill -KILL -f "lib.sh; fp_fetch" || true; pkill -INT -f "flatpak --user update" || true; wait $p || true
log "interrupted: $(du -sm /home/mu/cache | cut -f1) MB in the cache"; tail -5 "$OUT/pull-interrupted.txt"
log "resume, with a second fetch of the same commit waiting on the lock"
( u "fp_fetch $RTREF $RT_COMMIT \$URL \$KEY" > "$OUT/pull-waiter.txt" 2>&1 ) & w=$!
u "fp_fetch $RTREF $RT_COMMIT \$URL \$KEY; fp_fetch $REF $APP_COMMIT \$URL \$KEY" 2>&1 | tee "$OUT/pull.txt"
wait $w && log "waiting fetch: ok"; cat "$OUT/pull-waiter.txt"
r1=$(rx)
res pull_s $((SECONDS - t)); res pull_rx_MB $(( (r1 - r0) / 1048576 )); res cache_MB "$(du -sm /home/mu/cache | cut -f1)"
as_user ostree --repo=/home/mu/cache/flatpak/repo refs | tee -a "$OUT/results.txt"

log "warm cache: fetch again (must not pull)"
r0=$(rx); u "fp_fetch $RTREF $RT_COMMIT \$URL \$KEY; fp_fetch $REF $APP_COMMIT \$URL \$KEY"; res warm_fetch_rx_bytes $(( $(rx) - r0 ))

deploy() {   # deploy N [unshare -n]: build layer N from the cache (as the installer does), sealed
  local n="$1"; shift; t=$SECONDS
  "$@" runuser -u mu -- env HOME=/home/mu dbus-run-session -- bash -c \
    ". /home/mu/lib.sh; fp_deploy /home/mu/store/l$n/prusaslicer-flatpak \$URL \$KEY $RTREF@$RT_COMMIT $REF@$APP_COMMIT && fp_seal /home/mu/store/l$n" \
    > "$OUT/deploy$n.txt" 2>&1; rc=$?
  tail -8 "$OUT/deploy$n.txt"
  [ "$rc" = 0 ] || { res deploy$n fail; exit 1; }
  res deploy${n}_s $((SECONDS - t)); res layer${n}_MB "$(du -sm /home/mu/store/l$n | cut -f1)"
}
for n in 1 2; do log "offline deploy #$n (unshare -n: no network at all)"; deploy $n unshare -n; done
res cache_plus_layers_MB "$(du -smc /home/mu/cache /home/mu/store/l1 /home/mu/store/l2 | tail -1 | cut -f1)"
log "the cache is intact after building and sealing two layers"
as_user ostree --repo=/home/mu/cache/flatpak/repo fsck --quiet && res cache_fsck ok
FLATPAK_USER_DIR=/home/mu/store/l1/prusaslicer-flatpak as_user flatpak --user list --columns=ref,commit | tee -a "$OUT/results.txt"
log "damage one object in the cache: deploy #3 repairs it (downloads it again)"
obj="$(find /home/mu/cache/flatpak/repo/objects -name '*.file' -size +100k | head -1)"
chmod u+w "$obj"; printf 'x' >> "$obj"
deploy 3
grep -q "repairing the cache" "$OUT/deploy3.txt" && res repair ok
as_user ostree --repo=/home/mu/cache/flatpak/repo fsck --quiet && res cache_fsck_after_repair ok

log "slice offline from layer 1"
mkdir -p /home/mu/ps-data && chown mu /home/mu/ps-data
unshare -n runuser -u mu -- env HOME=/home/mu FLATPAK_USER_DIR=/home/mu/store/l1/prusaslicer-flatpak dbus-run-session -- \
  flatpak run --user --command=prusa-slicer --filesystem=host --nosocket=x11 --nosocket=wayland --env=LC_ALL=C.UTF-8 com.prusa3d.PrusaSlicer \
  --datadir /home/mu/ps-data --export-gcode --load /w/benchmarks/slice-print/profile_PETG-CF_0.4_0.2.ini /w/tools/s2/fixtures/plate.stl -o /home/mu/plate.gcode 2>&1 | tail -5
grep -E "^; (generated by|filament used \[g\]|estimated printing time \(normal)" /home/mu/plate.gcode | tee -a "$OUT/results.txt"
res layers "$(grep -c "^;LAYER_CHANGE" /home/mu/plate.gcode)"; res lines "$(wc -l < /home/mu/plate.gcode)"
grep -q "filament used \[g\] = 11.86" /home/mu/plate.gcode && res prusaslicer ok
log done
