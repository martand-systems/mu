// The μ dashboard's build (docs/design/dashboard.md §4.8). The output, ../share/dashboard/, is committed: the bundle
// that is committed is CI's artifact (§4.6.1). No source maps, no inlined assets, no module-preload polyfill, nothing
// fetched at runtime. The build also writes BUILD.json (the source fingerprint that tools/dashboard-build-info.py
// checks without Node, D28) and THIRD-PARTY.txt (the licences of the shipped packages, D34).
import { createHash } from "node:crypto";
import { existsSync, lstatSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import tailwindcss from "@tailwindcss/vite";
import react from "@vitejs/plugin-react";
import { defineConfig, type Plugin, type ProxyOptions } from "vite";

const here = import.meta.dirname;
// MU_DASH_OUT: a fault build goes elsewhere (the committed share/dashboard/ is only ever the real build)
const outDir = process.env.MU_DASH_OUT || join(here, "..", "share", "dashboard");

// ---- test faults (docs/design/dashboard.md §7.1: every page test is shown to fail with its fault put in). Each is a
// build-time constant __FAULT_<NAME>__, false in every real build, so the minifier removes the faulty code entirely;
// MU_DASH_FAULT=name[,name] turns faults on for a throw-away build (MU_DASH_OUT) or a Vitest run.
export const FAULTS = ["assume-features", "keep-fragment", "inner-html", "div-button", "faint-text", "style-tag",
  "radix-scrollarea", "inner-html-lib", "theme-in-bundle", "chart-fixed-colours", "boundary-shows-error",
  "server-down-as-offline", "copy-after-await", "interpolate-gap", "network-mode-default", "refused-as-offline",
  "mac-swap-mem", "faint-series", "copy-no-fallback", "violation-offline", "push-fragment"] as const;
const activeFaults = (process.env.MU_DASH_FAULT ?? "").split(",").filter(Boolean);
for (const f of activeFaults) {
  if (!(FAULTS as readonly string[]).includes(f)) throw new Error(`MU_DASH_FAULT: unknown fault ${f}`);
}
const faultDefines = Object.fromEntries(FAULTS.map((f) =>
  [`__FAULT_${f.toUpperCase().replace(/-/g, "_")}__`, JSON.stringify(activeFaults.includes(f))]));

// theme-in-bundle (D42's fault): the pre-paint script is left out of index.html and the bundle sets the theme instead
function themeFault(): Plugin {
  return {
    name: "mu-theme-fault",
    transformIndexHtml(html) {
      return activeFaults.includes("theme-in-bundle") ? html.replace(/\s*<script src="\/theme\.js"><\/script>/, "") : html;
    },
  };
}

// ---- the source fingerprint: the same files and the same hashing as tools/dashboard-build-info.py
const TOP = ["index.html", "package.json", "package-lock.json", ".nvmrc", "vite.config.ts", "tsconfig.json"];
const TREES = ["src", "public"];

function sha(data: Buffer | string): string {
  return createHash("sha256").update(data).digest("hex");
}

function walk(dir: string, out: string[]): void {
  for (const name of readdirSync(dir)) {
    if (name.startsWith(".")) continue;
    const p = join(dir, name);
    const st = lstatSync(p);
    if (st.isDirectory()) walk(p, out);
    else if (st.isFile()) out.push(relative(here, p).split(sep).join("/"));
  }
}

export function sourceInfo(): { source_sha256: string; files: number; lockfile_sha256: string | null; node: string } {
  const files = TOP.filter((f) => existsSync(join(here, f)) && lstatSync(join(here, f)).isFile());
  for (const t of TREES) if (existsSync(join(here, t))) walk(join(here, t), files);
  files.sort((a, b) => Buffer.compare(Buffer.from(a, "utf8"), Buffer.from(b, "utf8")));
  const h = createHash("sha256");
  for (const rel of files) h.update(Buffer.concat([Buffer.from(rel, "utf8"), Buffer.from([0]),
    Buffer.from(sha(readFileSync(join(here, rel))) + "\n")]));
  const lock = join(here, "package-lock.json");
  return {
    source_sha256: h.digest("hex"), files: files.length,
    lockfile_sha256: existsSync(lock) ? sha(readFileSync(lock)) : null,
    node: "v" + readFileSync(join(here, ".nvmrc"), "utf8").trim().replace(/^v/, ""),
  };
}

// ---- the shipped packages' licences: every lockfile entry that is not dev-only
type LockEntry = { version?: string; license?: string; dev?: boolean; devOptional?: boolean };

function thirdParty(): string {
  const lock = JSON.parse(readFileSync(join(here, "package-lock.json"), "utf8")) as { packages: Record<string, LockEntry> };
  const parts: string[] = [
    "Third-party software in the μ dashboard's page (share/dashboard/), with the licence texts as shipped by each",
    "package. Generated by the build from dashboard/package-lock.json; do not edit.",
    "",
  ];
  const names = Object.keys(lock.packages).filter((k) => k.startsWith("node_modules/") && !lock.packages[k]!.dev &&
    !lock.packages[k]!.devOptional).sort();
  for (const key of names) {
    const e = lock.packages[key]!;
    const dir = join(here, key);
    const name = key.slice(key.lastIndexOf("node_modules/") + "node_modules/".length);
    parts.push("=".repeat(100), `${name} ${e.version ?? ""} (${e.license ?? "UNKNOWN"})`, "=".repeat(100));
    let text = "";
    if (existsSync(dir)) {
      const f = readdirSync(dir).filter((n) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(n)).sort()[0];
      if (f) text = readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim();
    }
    parts.push(text || `(no licence file in the package; its package.json declares ${e.license ?? "nothing"})`, "");
  }
  return parts.join("\n") + "\n";
}

function buildFiles(): Plugin {
  return {
    name: "mu-build-files",
    apply: "build",
    closeBundle() {
      if (activeFaults.length) writeFileSync(join(outDir, "FAULT.txt"), activeFaults.join(",") + "\n");
      writeFileSync(join(outDir, "BUILD.json"), JSON.stringify({ schema: 1, ...sourceInfo() }, null, 1) + "\n");
      writeFileSync(join(outDir, "THIRD-PARTY.txt"), thirdParty());
    },
  };
}

// ---- the dev server: /api goes to `mu dashboard serve --dev` (fake nodes only), with its token
function devProxy(): Record<string, ProxyOptions> {
  const run = process.env.DASH_DEV_RUN ?? "";
  try {
    const info = JSON.parse(readFileSync(join(run, "dashboard.json"), "utf8")) as { port: number };
    const token = readFileSync(join(run, "dashboard.token"), "utf8").trim();
    return { "/api": { target: `http://127.0.0.1:${info.port}`, changeOrigin: true, headers: { "X-Mu-Token": token } } };
  } catch {
    return {};
  }
}

export default defineConfig(({ command }) => ({
  plugins: [react(), tailwindcss(), themeFault(), buildFiles()],
  define: faultDefines,
  server: { host: "127.0.0.1", port: 5173, strictPort: true, proxy: command === "serve" ? devProxy() : {} },
  build: {
    outDir,
    emptyOutDir: true,
    sourcemap: false,
    assetsInlineLimit: 0,
    modulePreload: { polyfill: false },
    target: ["safari16.4", "chrome111", "firefox128"],
    reportCompressedSize: false,
    // the vendor code (React, TanStack, Radix, uPlot, lucide) in its own chunk: a change to the app alone changes one
    // small file in the repository (§4.8)
    rolldownOptions: { output: { codeSplitting: { groups: [{ name: "vendor", test: /node_modules/ }] } } },
  },
  test: {
    environment: "jsdom",
    include: ["test/**/*.test.{ts,tsx}"],
  },
}));
